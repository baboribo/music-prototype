// Fictional, local-only content for the interface prototype.
// Shapes follow what YouTube Music browse pages expose (release type, year,
// owner, section titles); no field here is populated from a network response.

enum ArtworkTheme: String, CaseIterable, Hashable, Sendable {
    case midnight, coral, amber, forest, ocean, violet
}

/// Fixture shorthands so the tables below read as before.
extension Artwork {
    static let midnight = Artwork.theme(.midnight)
    static let coral = Artwork.theme(.coral)
    static let amber = Artwork.theme(.amber)
    static let forest = Artwork.theme(.forest)
    static let ocean = Artwork.theme(.ocean)
    static let violet = Artwork.theme(.violet)
}

struct Track: Identifiable, Hashable, Sendable {
    let id: String
    let title: String
    /// Display string as the service formats it (may list several artists).
    let artist: String
    let artistID: Artist.ID?
    let album: String
    let releaseID: Release.ID?
    let artwork: Artwork
    /// Seconds; nil where the service's listing omits it (Home shelves).
    let duration: Double?
    var isExplicit = false
    /// The service greys out rows it won't play here (region, removed uploads).
    var isPlayable = true
}

/// YouTube Music labels releases as Album, Single or EP; the page grammar is shared.
enum ReleaseKind: Hashable, Sendable {
    case album, single, ep

    var label: String {
        switch self {
        case .album: "앨범"
        case .single: "싱글"
        case .ep: "EP"
        }
    }
}

struct Release: Identifiable, Hashable, Sendable {
    let id: String
    let title: String
    /// nil when the listing doesn't say (artist carousels show only the year).
    let kind: ReleaseKind?
    let artistName: String
    let artistID: Artist.ID?
    let year: Int?
    let artwork: Artwork
    let trackIDs: [Track.ID]

    /// Apple Music suffixes non-album titles ("… - Single", "… - EP").
    var displayTitle: String {
        switch kind {
        case .album, nil: title
        case .single: "\(title) - Single"
        case .ep: "\(title) - EP"
        }
    }
}

/// Distinct because each comes from a different YouTube Music source and
/// is edited, attributed and refreshed differently.
enum PlaylistKind: Hashable, Sendable {
    case user
    case editorial
    /// Personal or seed mix ("나만의 믹스", "<곡> 믹스"), regenerated by the service.
    case mix
    /// Endless station seeded by a track/artist; starts playback instead of opening a page.
    case radio
    /// Service-maintained list such as liked music.
    case automatic
}

struct Playlist: Identifiable, Hashable, Sendable {
    let id: String
    let title: String
    let kind: PlaylistKind
    let owner: String
    let description: String?
    let artwork: Artwork
    let trackIDs: [Track.ID]
    /// Whether the listener owns (can edit) it; nil when the source doesn't say.
    var isOwned: Bool? = nil

    /// Own lists offer download instead of save; fixtures infer it from the kind.
    var isListenersOwn: Bool { isOwned ?? (kind == .user || kind == .automatic) }
}

struct Artist: Identifiable, Hashable, Sendable {
    let id: String
    let name: String
    let artwork: Artwork
    let description: String?
    /// Ordered as the artist page returns them; the view never invents sections.
    let sections: [ArtistSection]
    /// The listing's own second line: "27곡" for library artists, "구독자 60.1만명" for subscriptions.
    var byline: String? = nil
}

struct ArtistSection: Hashable, Sendable {
    enum Content: Hashable, Sendable {
        case songs([Track.ID])
        case releases([Release.ID])
        case playlists([Playlist.ID])
        case artists([Artist.ID])
    }
    let title: String
    let content: Content
}

/// Anything a shelf, search result or library entry can point at.
enum BrowseItem: Hashable, Sendable, Identifiable {
    case track(Track)
    case release(Release)
    case playlist(Playlist)
    case artist(Artist)

    var id: String {
        switch self {
        case .track(let v): "track.\(v.id)"
        case .release(let v): "release.\(v.id)"
        case .playlist(let v): "playlist.\(v.id)"
        case .artist(let v): "artist.\(v.id)"
        }
    }
}

/// Navigation values are identifiers so stacks stay cheap to store and restore.
enum Route: Hashable, Sendable {
    case release(Release.ID)
    case playlist(Playlist.ID)
    case artist(Artist.ID)
    case library(LibraryCategory)
}

/// The Library categories YouTube Music exposes; presentation follows Apple Music.
enum LibraryCategory: String, CaseIterable, Hashable, Sendable {
    case playlists, songs, albums, artists

    var title: String {
        switch self {
        case .playlists: "재생목록"
        case .songs: "노래"
        case .albums: "앨범"
        case .artists: "아티스트"
        }
    }

    var symbol: String {
        switch self {
        case .playlists: "music.note.list"
        case .songs: "music.note"
        case .albums: "square.stack"
        case .artists: "music.microphone"
        }
    }
}

/// A tile in the 3×3 빠른 선곡 grid: YouTube Music's listen-again module, where
/// "다시 듣기에 고정" items come first. Any item kind can be pinned.
enum QuickPick: Identifiable, Hashable, Sendable {
    case track(Track, pinned: Bool = false)
    case playlist(Playlist, pinned: Bool)
    case release(Release, pinned: Bool)
    case artist(Artist, pinned: Bool)

    var id: String {
        switch self {
        case .track(let v, _): "track.\(v.id)"
        case .playlist(let v, _): "playlist.\(v.id)"
        case .release(let v, _): "release.\(v.id)"
        case .artist(let v, _): "artist.\(v.id)"
        }
    }

    init(_ item: BrowseItem, pinned: Bool) {
        switch item {
        case .track(let v): self = .track(v, pinned: pinned)
        case .playlist(let v): self = .playlist(v, pinned: pinned)
        case .release(let v): self = .release(v, pinned: pinned)
        case .artist(let v): self = .artist(v, pinned: pinned)
        }
    }
}

